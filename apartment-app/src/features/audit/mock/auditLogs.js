// ── Helper functions ──────────────────────────────────────────────────────────

export function getAllAuditLogs() {
  return [...mockAuditLogs].sort(
    (a, b) => new Date(b.timestamp) - new Date(a.timestamp)
  );
}

export function getLoginLogs() {
  return getAllAuditLogs().filter(
    (log) =>
      log.module === AUDIT_MODULES.AUTHENTICATION &&
      (log.action === "User Login" ||
        log.action === "Failed Login Attempt" ||
        log.action === "User Logout")
  );
}

export function getAuditLogById(id) {
  return mockAuditLogs.find((log) => log.id === id) ?? null;
}

export function getAuditStats() {
  const logs = getAllAuditLogs();
  const today = new Date().toISOString().split("T")[0];
  const todayLogs = logs.filter((l) => l.timestamp.startsWith(today));
  const uniqueUsers = new Set(
    logs.map((l) => l.performedBy).filter((u) => u !== "System" && u !== "Unknown")
  );
  return {
    total: logs.length,
    todayCount: todayLogs.length,
    successful: logs.filter((l) => l.status === AUDIT_STATUS.SUCCESS).length,
    failed: logs.filter((l) => l.status === AUDIT_STATUS.FAILED).length,
    critical: logs.filter((l) => l.severity === AUDIT_SEVERITY.CRITICAL).length,
    uniqueUsers: uniqueUsers.size,
  };
}


